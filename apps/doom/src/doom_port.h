#ifndef DOOM_PORT_H
#define DOOM_PORT_H

#include <stdbool.h>
#include <stddef.h>
#include <stdint.h>

// The bridge between doomgeneric and the Morpthis SDK.
//
// Doom runs on a thread of the app's own. The game renders into an RGB565
// frame that the GUI thread copies into its canvas, and key events are queued
// by the GUI thread and drained by doomgeneric's DG_GetKey().
//
// The player loads the app in its own process, so Doom's I_Quit() and
// I_Error() must not call exit(). The core calls DG_RequestQuit() and
// DG_FatalError() instead; the hooks are compiled in with -DMORPTHIS_PORT.

typedef enum {
	DG_FRAME_NONE = 0,
	DG_FRAME_COPIED = 1, // a frame was copied into the caller's buffer
} dg_frame_result_t;

// Runs on the GUI thread when a new frame is ready to copy.
typedef void (*dg_port_notify_fn)(void);

// Runs on the Doom thread when the game loop has ended. The app posts its
// teardown from here, then joins the Doom thread.
typedef void (*dg_port_exit_fn)(void);

// Where the game goes on the portrait canvas. Landscape coordinates have the
// origin at the top-left of the panel as the user holds it: the panel's long
// edge is the landscape width. The port rotates its output 90 degrees
// counter-clockwise into the canvas, so the device is held with its top edge
// to the right.
typedef struct {
	int panel_w;  // canvas width in pixels (portrait)
	int panel_h;  // canvas height in pixels (portrait)
	int game_x0;  // game rectangle in landscape coordinates
	int game_y0;
	int game_w;
	int game_h;
} dg_geometry_t;

// Starts the Doom thread. `wad_path` is the absolute path of the IWAD and
// `base_dir` is the app folder (default.cfg and savegames are written there).
bool dg_port_start(const char *wad_path, const char *base_dir, const dg_geometry_t *geometry,
				   dg_port_notify_fn notify, dg_port_exit_fn exited);

// Joins the Doom thread. Sets the quit flag first, so the join is bounded by
// one game tick even if the thread is still running. GUI thread only, and
// never from the Doom thread itself. Frees the frame buffers.
void dg_port_join(void);

// Asks the game loop to stop at the end of the current tick. Any thread.
void dg_port_request_quit(void);

bool dg_port_running(void);

// True while Doom is in active play: a level is running with no menu or pause
// over it. The app forwards this to the player so the volume keys act as
// controls only during play and go back to the player's volume otherwise.
bool dg_port_gameplay_active(void);

// Copies the newest completed frame into `dst`, whose stride is `stride`
// pixels. The frame is already in the canvas's portrait orientation. GUI
// thread only.
dg_frame_result_t dg_port_copy_frame(uint16_t *dst, int stride);

// Copies the fatal error message, if the Doom thread died from I_Error().
// Returns false when there was no error. GUI thread, after dg_port_join().
bool dg_port_take_error(char *buffer, size_t size);

// Key queue, fed by the GUI thread and drained by DG_GetKey().
void dg_port_push_key(bool pressed, unsigned char key);

// Presses `key` now and releases it after `hold_ms` milliseconds. The release
// is generated by DG_GetKey() when the deadline passes, so no timer thread is
// needed. Used for physical buttons, which the player reports as press-only.
void dg_port_pulse_key(unsigned char key, uint32_t hold_ms);

// Hooks called by the Doom core on the Doom thread.
void DG_RequestQuit(void);
void DG_FatalError(const char *message);
const char *DG_GetBaseDir(void);

#endif /* DOOM_PORT_H */
